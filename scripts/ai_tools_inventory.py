"""Generate ai_tools_inventory.md from what is actually on disk.

The tables are derived, never hand-written: a hand-maintained matrix of which
skill exists under which harness goes stale the moment anyone adds one. Facts
that cannot be derived (why a skill is deliberately absent, how a plugin is
launched) live in ai_tools_notes.md and are appended verbatim.

Run from the repository root: `make inventory`.
"""

from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / "ai_tools_inventory.md"
NOTES = ROOT / "ai_tools_notes.md"

# Every harness that keeps a config tree at the repository root. Absent ones are
# reported as absent rather than silently dropped, because a harness that quietly
# disappeared is exactly the drift this file exists to catch.
PROVIDERS = [".claude", ".opencode", ".github"]

# Harnesses disagree on singular vs plural; both spellings load.
KINDS = {
    "Skills": ("skills", "skill"),
    "Commands": ("commands", "command", "prompts"),
    "Agents": ("agents", "agent"),
}


def entries(provider: str, dirnames: tuple[str, ...]) -> dict[str, Path]:
    """Map artifact name -> path, across every spelling of its directory."""
    found: dict[str, Path] = {}
    for dirname in dirnames:
        base = ROOT / provider / dirname
        if not base.is_dir():
            continue
        for child in sorted(base.iterdir()):
            if child.name.startswith("."):
                continue
            if child.is_dir() or child.is_symlink():
                # A symlink is kept even when it dangles: a broken link is the
                # drift most worth reporting, and dropping it would show the
                # artifact as merely absent.
                found.setdefault(child.name, child)
            elif child.suffix in {".md", ".toml"}:
                # Copilot names agents "<name>.agent.md" and prompts
                # "<name>.prompt.md"; keep the bare name so one artifact does not
                # appear as two rows across providers.
                stem = child.stem.removesuffix(".agent").removesuffix(".prompt")
                found.setdefault(stem, child)
    return found


def cell(provider: str, name: str, found: dict[str, Path]) -> str:
    path = found.get(name)
    if path is None:
        return "no"
    # A symlink means the provider shares another harness's copy rather than
    # keeping its own, which is the difference between "in sync" and "drifting".
    if not path.is_symlink():
        return "yes"
    return "link" if path.exists() else "broken link"


def table(present: list[str], kind: str, dirnames: tuple[str, ...]) -> list[str]:
    per_provider = {p: entries(p, dirnames) for p in present}
    names = sorted({n for found in per_provider.values() for n in found})
    if not names:
        return [f"## {kind}", "", "None.", ""]

    lines = [f"## {kind}", ""]
    lines.append("| " + kind.rstrip("s") + " | " + " | ".join(present) + " |")
    lines.append("|---|" + "---|" * len(present))
    for name in names:
        cells = [cell(p, name, per_provider[p]) for p in present]
        lines.append(f"| {name} | " + " | ".join(cells) + " |")
    lines.append("")
    return lines


def main() -> None:
    present = [p for p in PROVIDERS if (ROOT / p).is_dir()]
    absent = [p for p in PROVIDERS if p not in present]

    # Nothing outside the tree itself goes in the header: this file is committed,
    # so a branch name or timestamp would make every feature branch rewrite the
    # same line and conflict with every other one at merge time.
    out = [
        "# Repository AI Tool Inventory",
        "",
        "Generated by `make inventory`. Every table below is derived from the",
        "filesystem; edit the harness files and regenerate rather than editing",
        "this file. Durable notes live in `ai_tools_notes.md`.",
        "",
        "`yes` means the provider keeps its own copy, `link` means it symlinks",
        "another harness's copy, `broken link` means that symlink points at nothing,",
        "and `no` means absent.",
        "",
        f"Provider trees present: {', '.join(f'`{p}`' for p in present)}.",
    ]
    if absent:
        out.append(
            f"Not present: {', '.join(f'`{p}`' for p in absent)}."
        )
    out.append("")

    for kind, dirnames in KINDS.items():
        out += table(present, kind, dirnames)

    if NOTES.is_file():
        out += ["---", "", NOTES.read_text().strip(), ""]

    OUTPUT.write_text("\n".join(out) + "\n")
    counts = ", ".join(
        f"{k.lower()}={len({n for p in present for n in entries(p, d)})}"
        for k, d in KINDS.items()
    )
    print(f"wrote {OUTPUT.relative_to(ROOT)} ({counts})")


if __name__ == "__main__":
    main()
